-- 1. Each user's timezone (the browser sends it on signup/login)
alter table public.users
  add column if not exists timezone text not null default 'UTC';

-- 2. Unique keys that must be per-user / per-team, not global.
--    Your constraint list showed these columns as UNIQUE; if any of them is
--    unique on its own (e.g. tags.name), two users couldn't both have a tag
--    called "work". Drop any single-column unique key on these tables and
--    make sure the correct two-column one exists.
do $$
declare
  r record;
begin
  for r in
    select c.conname, c.conrelid::regclass as tbl
    from pg_constraint c
    where c.contype = 'u'
      and array_length(c.conkey, 1) = 1
      and c.conrelid in ('public.tags'::regclass,
                         'public.team_members'::regclass,
                         'public.task_reactions'::regclass)
  loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    raise notice 'dropped single-column unique % on %', r.conname, r.tbl;
  end loop;
end $$;

create unique index if not exists tags_user_id_name_key
  on public.tags (user_id, name);
create unique index if not exists team_members_team_id_user_id_key
  on public.team_members (team_id, user_id);
create unique index if not exists task_reactions_task_id_user_id_key
  on public.task_reactions (task_id, user_id);

-- 3. Deleting a user should delete their reminders (was NO ACTION)
do $$
declare
  c text;
begin
  for c in
    select conname from pg_constraint
    where conrelid = 'public.user_reminders'::regclass and contype = 'f'
  loop
    execute format('alter table public.user_reminders drop constraint %I', c);
  end loop;
end $$;

alter table public.user_reminders
  add constraint user_reminders_user_id_fkey
  foreign key (user_id) references public.users (id) on delete cascade;

-- 4. email_logs.id needs to fill itself in so the backend can log sends
do $$
begin
  if not exists (
    select 1 from pg_attribute
    where attrelid = 'public.email_logs'::regclass
      and attname = 'id' and attidentity <> ''
  ) and (
    select column_default from information_schema.columns
    where table_schema = 'public' and table_name = 'email_logs' and column_name = 'id'
  ) is null then
    alter table public.email_logs alter column id add generated by default as identity;
  end if;
end $$;

-- 5. Speeds up the reminder job and session lookups
create index if not exists idx_user_reminders_active on public.user_reminders (is_active);
create index if not exists idx_tasks_user_date on public.tasks (user_id, date_logged);
